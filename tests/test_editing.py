class OneAtATime:
    """A turn at the session, taken from every other copy on the machine.

    A Windows session has one clipboard and one foreground window, and this
    suite needs both. Eight copies at once (work/parallel_editing.py,
    2026-09-21) failed five times, every failure another copy's text arriving
    where this one's was put - and once an empty clipboard, which pastes
    nothing and reads exactly like a shortcut that did not fire. Serialising
    only the clipboard was not enough: the copies still queued with their
    windows open, whichever opened last held the foreground, and the one
    holding the lock got focus=None on every key. So the turn is taken
    BEFORE the window is built, and given up after it is destroyed.

    A NAMED MUTEX and not a lock file: the copies live in trees that share
    nothing, under work/mutants/run-*/w<i>/, so a file inside the tree would
    lock nothing. A kernel object is the session's, whatever the tree. A copy
    killed while holding it leaves it ABANDONED, which the next one takes.
    """

    NAME = "step2html-tests-one-window"
    OWNED, ABANDONED = 0x0, 0x80           # WAIT_OBJECT_0, and "the holder died"

    def __init__(self, seconds: float = 600.0):
        self.handle = None
        self.why = ""
        self.waited = 0.0
        if sys.platform != "win32":
            return
        import ctypes
        k32 = ctypes.windll.kernel32
        k32.CreateMutexW.restype = ctypes.c_void_p
        k32.CreateMutexW.argtypes = [ctypes.c_void_p, ctypes.c_int,
                                     ctypes.c_wchar_p]
        k32.WaitForSingleObject.restype = ctypes.c_uint
        k32.WaitForSingleObject.argtypes = [ctypes.c_void_p, ctypes.c_uint]
        k32.ReleaseMutex.argtypes = [ctypes.c_void_p]
        k32.CloseHandle.argtypes = [ctypes.c_void_p]
        self.k32 = k32
        handle = k32.CreateMutexW(None, 0, self.NAME)
        if not handle:
            self.why = f"CreateMutexW failed with error {ctypes.GetLastError()}"
            return
        waited = time.time()
        got = k32.WaitForSingleObject(handle, int(seconds * 1000))
        if got in (self.OWNED, self.ABANDONED):
            self.handle = handle
            self.waited = time.time() - waited
        else:
            k32.CloseHandle(handle)
            self.why = (f"another copy held the clipboard for {seconds:.0f}s "
                        f"(WaitForSingleObject returned 0x{got:x})")

    @property
    def held(self) -> bool:
        return self.handle is not None or sys.platform != "win32"

    def release(self) -> None:
        if self.handle is not None:
            self.k32.ReleaseMutex(self.handle)
            self.k32.CloseHandle(self.handle)
            self.handle = None


class Layouts:
    """The keyboard layout of THIS thread, switched and put back."""

    def __init__(self):
        import ctypes
        u32 = ctypes.windll.user32
        u32.GetKeyboardLayout.restype = ctypes.c_void_p
        u32.LoadKeyboardLayoutW.restype = ctypes.c_void_p
        u32.ActivateKeyboardLayout.restype = ctypes.c_void_p
        u32.ActivateKeyboardLayout.argtypes = [ctypes.c_void_p, ctypes.c_uint]
        self.u32 = u32
        self.before = u32.GetKeyboardLayout(0)

    def current(self) -> int:
        return self.u32.GetKeyboardLayout(0) & 0xFFFF          # the language part

    def use(self, klid: str, tries: int = 40) -> bool:
        """Make *klid* this thread's layout, and wait until it really is.

        Loading a layout is a request to the window manager, not an
        assignment: under load GetKeyboardLayout has answered with the old
        one for a few milliseconds afterwards, and every key generated in
        that window carried the wrong keysym.
        """
        want = int(klid, 16)
        for _ in range(tries):
            self.u32.LoadKeyboardLayoutW(klid, 1)              # KLF_ACTIVATE
            if self.current() == want:
                return True
            time.sleep(0.05)
        return False

    def restore(self) -> None:
        self.u32.ActivateKeyboardLayout(self.before, 0)


CHANGED = "the clipboard changed under the test - another program put something on it"


class Clipboard:
    """The real clipboard, set for the test and put back afterwards - as real
    data, never as Tk's promise (harness.put_clipboard_text says why).

    What the user had is read by ANOTHER process, as text and within 10 s:
    Tk's own clipboard_get waits for whoever owns a promise, up to 30 s, and
    it would wait holding the turn every other copy is waiting for. Each put
    and each copy of this suite's own notes the clipboard's sequence number
    in `ours`; a check that finds it moved knows the clipboard changed under
    it - the user's own copy, in the middle of a run - and the put-back knows
    not to put the user's old text over their newer one. What the user had
    is kept as TEXT: an image or files on the clipboard do not survive the
    suite, as they never did.
    """

    def __init__(self, root):
        self.root = root
        self.before, self.unread = clipboard_text_elsewhere()
        self.ours = clipboard_sequence()

    def put(self, text) -> str:
        """-> "" once *text* is on the clipboard as real data, else why not."""
        # Tk is told first that it owns the clipboard no more. A copy of its
        # own made while another program held the clipboard open never
        # reached Windows, yet Tk went on believing it owned the clipboard
        # and pasted that old text from its memory over what was put next
        # (work/clip96/desync_probe.py, twice of twice).
        self.root.tk.call("selection", "clear", "-displayof", self.root,
                          "-selection", "CLIPBOARD")
        why = put_clipboard_text(text)
        self.ours = clipboard_sequence()
        # A put while Tk owned the clipboard reaches Tk as a SelectionClear
        # in its queue, and until that is processed clipboard_get answers
        # from Tk's memory with the old text (work/clip96/seq_probe.py) -
        # the letting go above should have made it moot; this is the order
        # the probe measured.
        self.root.update()
        return why

    def claim(self) -> None:
        """Note the change this suite's own copy or cut has just made."""
        self.ours = clipboard_sequence()

    def changed(self) -> bool:
        """Whether somebody has changed the clipboard since this suite last did."""
        return clipboard_sequence() != self.ours

    def get(self) -> str:
        try:
            return self.root.clipboard_get()
        except tk.TclError:
            return ""

    def put_back(self) -> tuple:
        """("put", ""), ("left", why) or ("failed", why): harness.put_back_clipboard_text."""
        return put_back_clipboard_text(self.before or None, self.ours)


def pasted(paste, shown, expected, clip):
    """Paste until shown() is *expected*, at most ten times 50 ms apart:
    (True, detail, tries), (False, why, tries) - or (None, why, tries) when
    the clipboard changed under the test, which leaves nothing to judge.

    *paste* empties the target, pastes, and returns why the key went nowhere
    ("" when it arrived) - a key that went nowhere is a failure at once, not
    a reason to press again. Tk pastes from the Windows clipboard now that
    the text is real data, and while a window of another program has the
    clipboard open - one that reads it whenever it changes, as rdpclip.exe
    does in an RDP session - Tk's read fails at once and the paste inserts
    nothing (harness.clipboard_open_elsewhere): Simple 3D saw 6 such pastes
    in 308 on 2-16 copies. A paste that is never made fails all ten times;
    one the clipboard changed under is no evidence either way. Exactly
    *expected*, not containing it: a paste made twice must not pass.
    """
    for tries in range(1, 11):
        missed = paste() or ""
        if missed:
            return False, missed, tries
        if shown() == expected:
            return True, "" if tries == 1 else f"pasted on try {tries}", tries
        if clip.changed():
            return None, CHANGED, tries
        time.sleep(0.05)
    return False, f"{shown()!r} after ten pastes", tries


def refused(paste, shown, before, clip):
    """Paste ten times 50 ms apart into something that must not take it:
    (True, "", 10) when shown() stayed *before* every time, (False, why,
    tries) when a paste landed or the key went nowhere - or (None, why,
    tries) when nothing landed but the clipboard changed under the test.

    Ten, because one refused paste proves nothing while another program can
    hold the clipboard open: the paste then inserts nothing into anything,
    and an editable target looks exactly like a read-only one. And a key
    that never arrived proves nothing either - in session 0 of the 4090,
    where the window is never mapped, the log's check passed with no key
    delivered at all (23.10.2026).
    """
    for tries in range(1, 11):
        missed = paste() or ""
        if missed:
            return False, missed, tries
        if shown() != before:
            return False, f"{shown()[:45]!r} after paste {tries}", tries
        if clip.changed():
            return None, CHANGED, tries
        time.sleep(0.05)
    return True, "", tries


def copied(clip, wanted):
    """Whether this suite's own copy or cut is on the clipboard, after
    clip.claim(): (True, "") when wanted(text), (False, why) when not - or
    (None, why) when the clipboard changed after the claim. While Tk owns
    the clipboard it answers clipboard_get from its own memory, so this is
    what the shortcut copied, not a trip through Windows."""
    text = clip.get()
    if wanted(text):
        return True, ""
    if clip.changed():
        return None, CHANGED
    return False, text.strip()[:45] or "the clipboard is empty"


def judged(what, result):
    """check() a verdict from pasted(), refused() or copied() - or say why it
    could not be judged: a note, which is neither a pass nor a FAIL."""
    if result[0] is None:
        print(f"  note  {what} - not judged: {result[1]}")
    else:
        check(result[0], what, result[1])


def walk(widget):
    for child in widget.winfo_children():
        yield child
        yield from walk(child)


def watch(widget) -> None:
    """Record every KeyPress that reaches *widget*, ahead of its own bindings.

    A plain <KeyPress> binding on the widget would never fire: the shortcut
    is bound to <Control-KeyPress> on the same bindtag, Tk runs the more
    specific pattern only, and the handler returns "break" besides. A bindtag
    of this suite's own, first in the list, sees the event before any of that
    and returns None, so nothing downstream behaves differently.
    """
    widget.bind_class(WATCH, "<KeyPress>",
                      lambda event: DELIVERED.append(event.keysym))
    tags = tuple(widget.bindtags())
    if WATCH not in tags:
        widget.bindtags((WATCH,) + tags)


def ready(widget, tries: int = 20) -> str:
    """"" when a generated key will reach *widget*, else what is in the way.

    Tk hands a generated KeyPress to whatever ITS focus model believes has
    the focus, and drops the event when that is nobody. Two ways for it to
    be nobody, both measured rather than guessed:

      * the toplevel is not on screen yet - update() returns before the
        window is mapped under load, and the key goes nowhere;
      * another process took the foreground, so Tk saw a FocusOut. Then
        focus_set() is not enough: it leaves focus_displayof() at None and
        the key is still dropped (work/probe_focus.py). focus_force() puts
        it back, which is what the third step below does.

    Forcing is not gratuitous: this window is deliberately off every screen,
    and the suite already takes the foreground by opening it at all. On the
    suite's own desktop, where it lives since 2026-09-23, the foreground it
    takes is nobody's: the user's windows are on another desktop.
    """
    top = widget.winfo_toplevel()
    for attempt in range(tries):
        top.update()
        if top.winfo_ismapped() and top.winfo_viewable():
            widget.focus_set()
            top.update()
            if str(top.focus_displayof() or "") == str(widget):
                return ""
            if attempt:                    # asking politely did not work
                widget.focus_force()
                top.update()
                if str(top.focus_displayof() or "") == str(widget):
                    return ""
        time.sleep(0.05)
    return (f"the window never became ready for a key: "
            f"mapped={top.winfo_ismapped()}, viewable={top.winfo_viewable()}, "
            f"focus={top.focus_displayof()}, wanted {widget}")


def press(widget, keycode: int) -> str:
    """Ctrl + a physical key, the way Tk sees a real one: by keycode only.

    -> "" when the key was delivered, else the reason it was not - which is
    a different thing from a shortcut that fired and did nothing.
    """
    why = ready(widget)
    if why:
        return why
    watch(widget)
    DELIVERED.clear()
    widget.event_generate("<KeyPress>", keycode=keycode, state=CTRL)
    widget.winfo_toplevel().update()
    if not DELIVERED:
        top = widget.winfo_toplevel()
        return (f"the generated key never reached the widget: "
                f"mapped={top.winfo_ismapped()}, focus={top.focus_displayof()}")
    return ""


def clipboard_rules(root, app, field, clip, from_menu) -> None:
    """Each rule the checks of the clipboard stand on, made to happen once -
    with the menu, so on any desktop, keys or no keys. A program holding the
    clipboard open for 0.25 s at the paste, twice: once for a paste that must
    land, once for one a check expects refused. A try every ~51 ms lands the
    paste on about the sixth of ten, ~200 ms from either end; 0.4 s landed it
    on try 9 in 84 runs of 84, ~60 ms from the last (23.10.2026). Then a put by "another
    program" after this suite's copy, and after its put: neither check is
    judged, and nor is a refused paste once another program has emptied the
    clipboard. A copy made while the clipboard is held open does not outlive
    the next put. And the put-back, told the clipboard changed since this
    suite's own last change, leaves what is there."""
    holder = hold_clipboard_open(0.25)
    held = clipboard_open_elsewhere()
    verdict, why, tries = pasted(from_menu, app.step_path.get, "D:/pasted/from menu", clip)
    if holder is not None:
        holder.wait(10)
    judged("a paste that finds the clipboard held open by another program is retried "
           "until it is free",
           (None, "the holder was not holding the clipboard at the paste") if not held else
           (verdict, why) if verdict is None else
           (verdict and tries > 1, f"{verdict}, {why}, try {tries}"))

    # On an editable field a refused paste is a wrong answer: one held up at
    # first must still land, within the ten chances.
    holder = hold_clipboard_open(0.25)
    held = clipboard_open_elsewhere()
    verdict, why, tries = refused(from_menu, app.step_path.get, "", clip)
    if holder is not None:
        holder.wait(10)
    judged("a paste a check expects refused is given ten chances too: held up at first, "
           "it lands on a later one",
           (None, "the holder was not holding the clipboard at the paste") if not held else
           (verdict, why) if verdict is None else
           (verdict is False and tries > 1, f"{verdict}, {why}, try {tries}"))

    field.delete(0, "end")
    field.insert(0, "D:/copied/from menu")
    field.selection_range(0, "end")
    editing.edit_menu(field).invoke(1)                   # Copy
    root.update()
    clip.claim()
    judged("Copy from the menu puts the selection on the clipboard",
           copied(clip, lambda text: text == "D:/copied/from menu"))
    put = put_clipboard_text("D:/another/program")       # another program's copy, after this one's
    root.update()
    verdict, why = copied(clip, lambda text: text == "D:/copied/from menu")
    check(not put and verdict is None, "a copy the clipboard changed under is not judged either way",
          put or f"{verdict}, {why}")
    verdict, why, tries = pasted(from_menu, app.step_path.get, "D:/pasted/from menu", clip)
    check(verdict is None, "a paste the clipboard changed under is not judged either way",
          f"{verdict}, {why}, try {tries}")
    # Emptied by another program: a paste then inserts nothing anywhere, so a
    # field that takes pastes looks like one that refuses them.
    put = put_clipboard_text(None)
    verdict, why, tries = refused(from_menu, app.step_path.get, "", clip)
    check(not put and verdict is None,
          "nor is a refused paste, when the clipboard changed under it and nothing landed",
          put or f"{verdict}, {why}, try {tries}")

    # A copy made while another program holds the clipboard open never
    # reaches Windows, and Tk goes on answering from its memory unless the
    # next put tells it to let go (Clipboard.put).
    field.delete(0, "end")
    field.insert(0, "D:/copied/while held")
    field.selection_range(0, "end")
    holder = hold_clipboard_open(0.6)
    held = clipboard_open_elsewhere()
    editing.edit_menu(field).invoke(1)                   # Copy
    root.update()
    if holder is not None:
        holder.wait(10)
    reached, _ = clipboard_text_elsewhere()
    put = clip.put("D:/put/after the held copy")
    judged("after a copy that never reached Windows, what is put next is what pastes",
           (None, "the holder was not holding the clipboard at the copy") if not held else
           (None, "the copy reached Windows all the same") if reached == "D:/copied/while held" else
           (False, put) if put else
           pasted(from_menu, app.step_path.get, "D:/put/after the held copy", clip))

    clip.claim()                                         # those puts were this suite's own
    left, why = put_back_clipboard_text("D:/must/not/land", clip.ours - 1)
    seen, _ = clipboard_text_elsewhere()
    check(left == "left" and seen != "D:/must/not/land",
          "the user's text is not put back over a newer one - the clipboard changed since "
          "this suite's own last change", f"{left}, {why}, {seen!r}")


def main():
    # The window below is mapped - it has to be - on a desktop nobody looks
    # at: on the user's it came up in the taskbar and took the foreground on
    # every run (measured 2026-09-23). Before the first Tk(), or it is too late.
    why = keep_windows_off_screen()
    if why:
        print(f"note: the window is shown on this desktop - {why}")

    print("[1] the handler's decisions, on fake events")
    check_decisions()

    print("\n[2] the window's fields carry the menu and the shortcuts")
    # Under work/tmp on D:, and with a settings file of the test's own: the
    # window reads CONFIG in __init__, and the developer's real one carries a
    # geometry and a window_state - a remembered "zoomed" would fight the
    # off-screen placement three lines below.
    with scratch("editing-") as tmp:
        here = Path(tmp).resolve()
        check(here.is_relative_to((ROOT / "work" / "tmp").resolve()),
              "the suite writes under work/tmp, not the system TEMP on C:",
              str(here))
        gui.CONFIG = Path(tmp) / "step2html_config.json"

        # Before the window: a copy waiting with its window already open is a
        # copy holding the foreground away from whoever has the turn.
        turn = OneAtATime()
        check(turn.held,
              "the suite has the machine's clipboard and foreground to itself",
              turn.why or f"waited {turn.waited:.1f}s for its turn")

        root = tk.Tk()
        app = gui.App(root)
        # Beyond the edge of every screen: mapped, so that generated keys are
        # delivered, and nowhere anyone can see. Placed AFTER App(), which
        # restores the remembered position first.
        vx, vy, _w, _h = virtual_screen((0, 0, root.winfo_screenwidth(),
                                         root.winfo_screenheight()))
        root.geometry(f"+{vx - 4000}+{vy - 4000}")
        root.update()

        # type(), not isinstance: a Spinbox is an Entry too, and the arrows do
        # not get an edit menu - the same rule Simple 3D's window follows.
        entries = [w for w in walk(root) if type(w) is ttk.Entry]
        named = {app.step_entry, app.out_entry, app.title_entry,
                 app.deflection_entry, app.budget_entry}
        check(set(entries) == named, "every Entry in the window is one of the five named",
              f"{len(entries)} found")
        check(all(w.bind("<Button-3>") for w in entries), "every Entry answers a right-click")
        check(all(w.bind("<Control-KeyPress>") for w in entries),
              "and carries the layout-blind shortcuts")
        check(bool(app.log_view.bind("<Control-KeyPress>"))
              and not app.log_view.bind("<Button-3>"),
              "the log has the shortcuts and no menu")

        field = app.step_entry
        menu = editing.edit_menu(field)
        labels = [menu.entrycget(i, "label") for i in range(menu.index("end") + 1)
                  if menu.type(i) == "command"]
        check(labels == ["Cut", "Copy", "Paste", "Select all"],
              "Cut, Copy, Paste, Select all", str(labels))

        # From reading what the user had on the clipboard to putting it back,
        # this copy holds the turn taken above. The text goes on as real data,
        # never as Tk's promise, and what the user had is read by another
        # process (Clipboard; harness.put_clipboard_text says why).
        clip = Clipboard(root) if sys.platform == "win32" and turn.held else None
        layouts = Layouts() if sys.platform == "win32" else None

        def from_menu() -> str:
            field.delete(0, "end")
            editing.edit_menu(field).invoke(2)               # Paste
            root.update()
            return ""

        try:
            if clip is None:
                print("  skip  the clipboard:", turn.why if sys.platform == "win32"
                      else "not Windows - the text goes on as Win32 real data")
            else:
                if clip.unread:
                    print(f"  note  the text the clipboard held before cannot be read, so it "
                          f"is emptied at the end, not put back: {clip.unread}")
                put = clip.put("D:/pasted/from menu")
                seen, why = clipboard_text_elsewhere()
                judged("the text is put as real data: another process reads it while this "
                       "copy pumps nothing",
                       (None, CHANGED) if clip.changed() else
                       (not put and seen == "D:/pasted/from menu", put or why or repr(seen)))
                judged("Paste from the menu fills the field",
                       (False, put) if put else
                       pasted(from_menu, app.step_path.get, "D:/pasted/from menu", clip))
                clipboard_rules(root, app, field, clip, from_menu)
            field.delete(0, "end")
            field.insert(0, "D:/selected/all")
            editing.edit_menu(field).invoke(4)               # Select all
            root.update()
            check(field.selection_present() and field.selection_get() == "D:/selected/all",
                  "Select all selects it")

            class _Click:
                x_root = y_root = 0

            app.job = object()                                # a build in flight, as far as the fields know
            check(editing.show_edit_menu(_Click(), field, app._frozen) is None,
                  "no menu while a build runs")
            app.job = None
            check(not app._frozen(), "and the fields thaw with the job")

            # That was the function. This is the FIELD: attach() is handed the
            # window's own _frozen, and a field wired without it would show the
            # menu mid-build while the check above went on passing. The pop-up
            # itself is replaced, so nothing appears and nothing grabs.
            asked = []
            real_show, editing.show_edit_menu = editing.show_edit_menu, (
                lambda event, w, frozen: asked.append((w is field, frozen())))
            try:
                app.job = object()
                field.event_generate("<Button-3>", x=5, y=5)
                root.update()
                app.job = None
                field.event_generate("<Button-3>", x=5, y=5)
                root.update()
            finally:
                editing.show_edit_menu = real_show
            check(asked == [(True, True), (True, False)],
                  "the field's own right-click carries the window's frozen flag",
                  str(asked))

            print("\n[3] the keys themselves, with the layout really switched")
            if layouts is None:
                print("  skip  not Windows: the layout cannot be switched here")
            elif not turn.held:
                print("  skip  no turn at the clipboard:", turn.why)
            else:
                check(layouts.use(RUSSIAN), "the Russian layout is active for this thread",
                      f"0x{layouts.current():04x}")

                # First the bug, on a field WITHOUT the fix: what Tk does on its own.
                bare = ttk.Entry(root)
                bare.place(x=0, y=0)
                root.update()
                put = clip.put("nothing should arrive")
                missed = press(bare, V)
                keysym = DELIVERED[0] if DELIVERED else None
                check(not missed and not put and keysym not in (None, "v", "V")
                      and bare.get() == "",
                      "Tk's own Ctrl+V does nothing under the Russian layout",
                      missed or put or f"keysym {keysym!r}, field {bare.get()!r}")
                bare.destroy()

                # Then the window's field, with the fix.
                def into_field() -> str:
                    field.delete(0, "end")
                    return press(field, V)

                put = clip.put("D:/layout/blind")
                judged("Ctrl+V pastes into the STEP field",
                       (False, put) if put else
                       pasted(into_field, app.step_path.get, "D:/layout/blind", clip))
                # Put in by hand, whatever that paste left.
                field.delete(0, "end")
                field.insert(0, "D:/layout/blind")
                missed = press(field, A)
                selected = (field.selection_get()
                            if field.selection_present() else None)
                check(selected == "D:/layout/blind", "Ctrl+A selects it all",
                      missed or (selected if selected is not None
                                 else "nothing is selected"))
                put = clip.put("")
                missed = press(field, C)
                clip.claim()
                judged("Ctrl+C copies the selection",
                       (False, missed or put) if missed or put else
                       copied(clip, lambda text: text == "D:/layout/blind"))
                # Emptied again first: the copy above left the same text there,
                # and a cut that only deleted would have passed on it.
                put = clip.put("")
                missed = press(field, X)
                clip.claim()
                judged("Ctrl+X cuts it",
                       (False, missed or put) if missed or put else
                       (False, f"field {app.step_path.get()!r}") if app.step_path.get() else
                       copied(clip, lambda text: text == "D:/layout/blind"))

                # The log: Copy and Select all work, Paste stays a no-op.
                app.clear_log()
                app.log("hello from the log")
                missed = press(app.log_view, A) or press(app.log_view, C)
                clip.claim()
                judged("the log copies under the Russian layout",
                       (False, missed) if missed else
                       copied(clip, lambda text: "hello from the log" in text))
                # Something the log does NOT already say: pasting what was just
                # copied over the selection that was just made leaves the same
                # text behind, so it cannot tell a refused paste from a real one.
                put = clip.put("pasted over the record of the build")
                judged("and Ctrl+V leaves the read-only log alone",
                       (False, put) if put else
                       refused(lambda: press(app.log_view, V),
                               lambda: app.log_view.get("1.0", "end").strip(),
                               "hello from the log", clip))

                # And the Latin layout: once, not twice.
                check(layouts.use(ENGLISH), "the English layout is active",
                      f"0x{layouts.current():04x}")
                put = clip.put("once")
                judged("under a Latin layout Ctrl+V pastes exactly once",
                       (False, put) if put else
                       pasted(into_field, app.step_path.get, "once", clip))
        finally:
            if layouts is not None:
                layouts.restore()
                check(layouts.u32.GetKeyboardLayout(0) == layouts.before,
                      "the layout is back to what it was")
            if clip is not None:
                done, why = clip.put_back()
                after = clipboard_sequence()
                seen, why_not = clipboard_text_elsewhere()
                if done == "left":
                    print(f"  note  the user's text is not put back - {why}: what is there "
                          f"is theirs, and newer")
                else:
                    judged("and the user's own text is put back as real data, so it outlives "
                           "this copy",
                           (None, CHANGED) if clipboard_sequence() != after else
                           (done == "put" and not why_not and seen == (clip.before or None),
                            why or why_not or repr(seen)))
            turn.release()
            root.destroy()


if __name__ == "__main__":
    mp.freeze_support()
    sys.exit(run(main, "editing a field"))
