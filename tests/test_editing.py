"""Editing a field: the right-click menu, and Ctrl+C/V/X/A under a keyboard
layout that is not Latin - with the layout REALLY switched, not faked.

Tk binds its shortcuts to the keysym, the Latin letter, so under a Russian
layout the V key arrives as "??" on this Tk and nothing fires; this suite
measures that first, on a field without the fix, and then the fix on the
window's own fields. The layout is switched for this process's thread alone
(LoadKeyboardLayoutW / ActivateKeyboardLayout), the window sits on a desktop
of its own (harness.keep_windows_off_screen) - and beyond the edge of every
screen as well, for when that desktop cannot be had - and the previous
layout is put back at the end: the user's own session is untouched. Key
events are generated by keycode ALONE, so Tk derives the keysym the way it
does for a real key: from the virtual-key code and the active layout. A
withdrawn window drops generated key events, which is why this one is
mapped.

Where the layout cannot be switched (not Windows) that half is skipped and
says so; the handler's decisions are pinned by fake events either way.

FOUR THINGS THIS SUITE CANNOT ASSUME, each of which has failed:

  * The clipboard is ONE per Windows session, and so is the foreground. The
    mutation runner puts several copies of this suite on the machine at
    once: measured on 2026-09-21, eight parallel copies, five failed - one
    copy's clipboard rewritten by another between the put and the key that
    pastes it. So the copies take turns, on a named mutex (OneAtATime), and
    a copy takes its turn before it opens a window at all.
  * Text put with Tk's clipboard_append is only PROMISED, and dies with the
    process: the text the clipboard held before this suite, "put back" that
    way, was gone after every run (6 of 6, 23.10.2026, work/clip96/
    defect_probe.py). So the text goes on as real data
    (harness.put_clipboard_text), what was there is read by another process
    within a limit and put back the same way - but never over a newer copy
    of the user's. Reading the real clipboard brings the rest of the session
    in: while another program holds the clipboard open a paste inserts
    nothing, so a paste is given ten chances (pasted(), refused()), and a
    copy of Tk's own never reaches Windows while Tk goes on pasting it from
    its memory, so every put first tells Tk to let go (Clipboard.put); and
    the user's own copy can land in the middle of a check, which then says
    "not judged" instead of failing (Clipboard, judged()).
  * A generated key goes to whatever TK believes has the focus, and Tk
    believes nobody has it the moment another process's window takes the
    foreground. Measured (work/probe_focus.py): with a second window in
    front, focus_displayof() is None, focus_set() does not change that and
    the generated key is silently dropped; focus_force() does, and the key
    arrives. So ready() asks, waits, and forces - and a key that still goes
    nowhere says exactly that instead of leaving a check to fail with an
    empty keysym and no cause.
  * A layout does not become active the instant it is asked for. Retried,
    with a bound, and the failure names the layout that IS active.
"""
